"""Release metadata shared by the build scripts.

Sources of truth:
- ``version.toml`` (repository root): release version and minimum Archipelago version.
- ``release/static_pak_manifest.json``: pinned static pak SHA-256 and file count.

``Mod/ClientVersion.h`` and ``Mod/StaticPakPin.h`` are generated from these files by
``sync_generated_headers``; edit the sources, never the headers.
"""

from __future__ import annotations

import hashlib
import json
import tomllib
from dataclasses import dataclass
from pathlib import Path


REPOSITORY = Path(__file__).resolve().parents[1]
VERSION_FILE = REPOSITORY / "version.toml"
PAK_MANIFEST = REPOSITORY / "release/static_pak_manifest.json"
CLIENT_VERSION_HEADER = REPOSITORY / "Mod/ClientVersion.h"
STATIC_PAK_PIN_HEADER = REPOSITORY / "Mod/StaticPakPin.h"

# Seed-specific True Randomizer assets that must never ship in the static pak.
GENERATED_ASSET_STEMS = ("DifficultSelecter", "EntryNameSetter", "VersionNumber")

GENERATED_NOTICE = (
    "// Generated by tools2/release_info.py from {source}. Do not edit by hand.\n"
)


@dataclass(frozen=True)
class ReleaseInfo:
    version: str
    min_ap_version: str

    @property
    def min_ap_version_parts(self) -> tuple[int, int, int]:
        parts = tuple(int(part) for part in self.min_ap_version.split("."))
        if len(parts) != 3:
            raise ValueError(f"min_archipelago_version must be X.Y.Z: {self.min_ap_version!r}")
        return parts


@dataclass(frozen=True)
class PakPin:
    sha256: str
    file_count: int


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def load_version() -> ReleaseInfo:
    data = tomllib.loads(VERSION_FILE.read_text(encoding="utf-8"))
    return ReleaseInfo(data["version"], data["min_archipelago_version"])


def load_pak_manifest() -> dict:
    return json.loads(PAK_MANIFEST.read_text(encoding="utf-8"))


def load_pak_pin() -> PakPin:
    manifest = load_pak_manifest()
    return PakPin(manifest["sha256"], manifest["file_count"])


def write_pak_pin(pin: PakPin) -> None:
    """Record a reviewed static pak as the pinned one and refresh the generated headers."""
    manifest = load_pak_manifest()
    manifest["sha256"] = pin.sha256
    manifest["file_count"] = pin.file_count
    PAK_MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    sync_generated_headers()


def _write_if_changed(path: Path, content: str) -> bool:
    # Leave unchanged headers alone so MSBuild does not rebuild their dependents.
    if path.is_file() and path.read_text(encoding="utf-8") == content:
        return False
    path.write_text(content, encoding="utf-8")
    return True


def sync_generated_headers() -> list[Path]:
    """Regenerate the C++ headers derived from the release metadata; return changed paths."""
    info = load_version()
    major, minor, build = info.min_ap_version_parts
    client_version = (
        "#pragma once\n\n"
        + GENERATED_NOTICE.format(source="version.toml")
        + "\nnamespace ClientVersion {\n\n"
        f'inline constexpr char Display[] = "{info.version}";\n\n'
        "namespace ArchipelagoProtocol {\n\n"
        f"inline constexpr int Major = {major};\n"
        f"inline constexpr int Minor = {minor};\n"
        f"inline constexpr int Build = {build};\n\n"
        "}  // namespace ArchipelagoProtocol\n\n"
        "}  // namespace ClientVersion\n"
    )
    static_pak_pin = (
        "#pragma once\n\n"
        + GENERATED_NOTICE.format(source="release/static_pak_manifest.json")
        + "\n#include <string_view>\n\n"
        "inline constexpr std::string_view STATIC_PAK_SHA256 =\n"
        f'    "{load_pak_pin().sha256}";\n'
    )
    changed = []
    for path, content in (
        (CLIENT_VERSION_HEADER, client_version),
        (STATIC_PAK_PIN_HEADER, static_pak_pin),
    ):
        if _write_if_changed(path, content):
            changed.append(path)
    return changed


if __name__ == "__main__":
    for path in sync_generated_headers():
        print(f"updated {path}")
